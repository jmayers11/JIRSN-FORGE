    public static string Describe(string transactionSet) => transactionSet switch
    {
        "850" => "purchase order (850)",
        "855" => "order acknowledgment (855)",
        "856" => "ship notice (856)",
        "860" => "purchase order change (860)",
        "810" => "invoice (810)",
        "997" => "functional acknowledgment (997)",
        _ => $"transaction set {transactionSet}",
    };

    /// <summary>A transaction's segments as text (ST … SE), for the document log.</summary>
    public static string Render(X12Transaction t)
    {
        ArgumentNullException.ThrowIfNull(t);
        var sb = new StringBuilder();
        sb.Append("ST*").Append(t.Code).Append('*').Append(t.ControlNumber).Append("~\n");
        foreach (var s in t.Segments) sb.Append(s.Id).Append(string.Concat(s.Elements.Select(e => "*" + e))).Append("~\n");
        sb.Append("SE*").Append((t.Segments.Count + 2).ToString(CultureInfo.InvariantCulture)).Append('*').Append(t.ControlNumber).Append("~\n");
        return sb.ToString();
    }

    /// <summary>Reads back a transaction rendered by <see cref="Render"/>.</summary>
    public static IReadOnlyList<X12Segment> Segments(string content) =>
        (content ?? string.Empty).Split('~').Select(s => s.Trim('\r', '\n', ' ')).Where(s => s.Length > 0)
            .Select(s => s.Split('*')).Select(p => new X12Segment(p[0], p.Skip(1).ToList())).Where(s => s.Id is not ("ST" or "SE")).ToList();
}
