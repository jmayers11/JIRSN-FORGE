/// <summary>
/// Trading partners, EDI documents, API keys and webhooks (owner decisions 2026-11-01). An integration administrator keeps partners,
/// keys and webhooks; the system records what arrives and what goes out; people review and reprocess or reject what could not be mapped.
/// </summary>
public sealed class InterchangeService(CommandPipeline pipeline, IInterchangePartyResolver parties)
{
    public const string SourceContext = "Interchange";

    /// <summary>Delays before each retry of a failed webhook delivery; after the last, it is marked failed.</summary>
    public static readonly IReadOnlyList<TimeSpan> RetryDelays = [TimeSpan.FromMinutes(1), TimeSpan.FromMinutes(5), TimeSpan.FromMinutes(30), TimeSpan.FromHours(2), TimeSpan.FromHours(12)];

    private const string Document = "InterchangeDocument";

    private static readonly IReadOnlySet<string> CustomerSets = new HashSet<string>(StringComparer.Ordinal) { "855", "856", "810" };
    private static readonly IReadOnlySet<string> SupplierSets = new HashSet<string>(StringComparer.Ordinal) { "850" };

    public Task<CommandResult> SavePartnerAsync(SavePartner c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var code = BusinessCode.Require(c.Code, "Partner");
        var spec = new CommandSpec(SourceContext, nameof(SavePartner), Permissions.InterchangeManage, ResourceRef.Of("TradingPartner", code), ReasonRequired: true);
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var name = BusinessCode.RequireName(c.Name, "Partner");
            string? party = null;
            if (c.Kind != PartnerKind.System)
            {
                party = BusinessCode.Require(c.PartyCode, c.Kind == PartnerKind.Customer ? "Customer" : "Supplier");
                if (await parties.PartyNameAsync(uow, c.Kind, party, ct) is null)
                    throw new CommandRejectedException("unknown_party", $"There is no {c.Kind.ToString().ToLowerInvariant()} {party}.");
                if (await uow.Store<IInterchangeLookup>().FindPartnerByPartyAsync(c.Kind, party, ct) is { } other && other.Code != code)
                    throw new CommandRejectedException("party_taken", $"{c.Kind} {party} already trades as partner {other.Code}.");
            }

            var edi = new[] { c.EdiQualifier, c.EdiId, c.OurQualifier, c.OurId }.Select(v => X12.Clean(v)).ToArray();
            var usesEdi = edi.All(v => v.Length > 0);
            if (!usesEdi && edi.Any(v => v.Length > 0))
                throw new CommandRejectedException("edi_ids_incomplete", "EDI needs the partner's qualifier and id and ours as the partner knows us, or none of them.");
            if (usesEdi && (edi[0].Length != 2 || edi[2].Length != 2 || edi[1].Length > 15 || edi[3].Length > 15))
                throw new CommandRejectedException("invalid_edi_id", "ISA qualifiers are two characters and ids at most 15.");
            if (c.Kind == PartnerKind.System && usesEdi) throw new CommandRejectedException("system_no_edi", "A system partner uses the API and webhooks, not EDI.");
            if (usesEdi && await uow.Store<IInterchangeLookup>().FindPartnerByEdiAsync(edi[0], edi[1], ct) is { } same && same.Code != code)
                throw new CommandRejectedException("edi_id_taken", $"Partner {same.Code} already sends as {edi[0]}/{edi[1]}.");
            var outbound = (c.Outbound ?? []).Select(s => s.Trim()).Where(s => s.Length > 0).Distinct(StringComparer.Ordinal).OrderBy(s => s, StringComparer.Ordinal).ToList();
            var allowed = c.Kind switch { PartnerKind.Customer => CustomerSets, PartnerKind.Supplier => SupplierSets, _ => new HashSet<string>() };
            if (outbound.FirstOrDefault(s => !allowed.Contains(s)) is { } bad)
                throw new CommandRejectedException("invalid_outbound", $"Forge does not send {bad} to a {c.Kind.ToString().ToLowerInvariant()}.");
            if (outbound.Count > 0 && !usesEdi) throw new CommandRejectedException("edi_ids_required", "Sending EDI documents needs the EDI ids.");
            var before = await uow.Store<IInterchangeLookup>().FindPartnerAsync(code, ct);
            var partner = new TradingPartnerInfo(code, name, c.Kind, party, usesEdi ? edi[0] : null, usesEdi ? edi[1] : null, usesEdi ? edi[2] : null, usesEdi ? edi[3] : null,
                outbound, c.Active, c.Test, context.Actor, now);
            if (before is not null && before.Kind != c.Kind) throw new CommandRejectedException("kind_fixed", "A partner's kind cannot change; add a new partner.");
            await uow.Store<IInterchangeStore>().UpsertPartnerAsync(partner, ct);
            return new CommandOutcome(CommandResult.Ok(code, $"Partner {code} ({name}) {(before is null ? "added" : "updated")}."),
                [pipeline.Event(new TradingPartnerChanged(code, before is null ? "Added" : "Updated"), context, SourceContext, "TradingPartner", code)],
                new AuditChange("TradingPartner", code, before is null ? null : CanonicalJson.Serialize(before), CanonicalJson.Serialize(partner)));
        }, ct);
    }

    public Task<CommandResult> IssueApiKeyAsync(IssueApiKey c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var code = BusinessCode.Require(c.PartnerCode, "Partner");
        var spec = new CommandSpec(SourceContext, nameof(IssueApiKey), Permissions.InterchangeManage, ResourceRef.Of("TradingPartner", code), ReasonRequired: true);
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var partner = await uow.Store<IInterchangeLookup>().FindPartnerAsync(code, ct) ?? throw new CommandRejectedException("partner_not_found", $"Partner {code} does not exist.");
            if (!partner.Active) throw new CommandRejectedException("partner_inactive", $"Partner {code} is inactive.");
            var scopes = (c.Scopes ?? []).Distinct(StringComparer.Ordinal).OrderBy(s => s, StringComparer.Ordinal).ToList();
            if (scopes.Count == 0 || scopes.Any(s => !ApiScopes.All.Contains(s)))
                throw new CommandRejectedException("invalid_scopes", $"Choose one or more of: {string.Join(", ", ApiScopes.All)}.");
            if (scopes.Contains(ApiScopes.Orders) && partner.Kind != PartnerKind.Customer) throw new CommandRejectedException("invalid_scopes", "Only customers submit and read orders.");
            if (scopes.Contains(ApiScopes.PurchaseOrders) && partner.Kind != PartnerKind.Supplier) throw new CommandRejectedException("invalid_scopes", "Only suppliers read purchase orders.");
            if (scopes.Contains(ApiScopes.Edi) && !partner.UsesEdi) throw new CommandRejectedException("invalid_scopes", "Submitting EDI needs the partner's EDI ids.");
            if (string.IsNullOrWhiteSpace(c.Hash) || c.Hash.Length != 64 || string.IsNullOrWhiteSpace(c.Prefix) || c.Prefix.Length > 16)
                throw new CommandRejectedException("invalid_key", "The key was not generated correctly.");
            var key = new ApiKeyInfo(0, code, c.Prefix, scopes, context.Actor, now, null, null, null);
            var id = await uow.Store<IInterchangeStore>().InsertApiKeyAsync(key, c.Hash, ct);
            var text = id.ToString(CultureInfo.InvariantCulture);
            return new CommandOutcome(CommandResult.Ok(text, $"API key {c.Prefix}… issued to {partner.Name} for {string.Join(", ", scopes)}. Copy it now; Forge keeps only its hash."),
                [pipeline.Event(new TradingPartnerChanged(code, "KeyIssued"), context, SourceContext, "TradingPartner", code)],
                new AuditChange("ApiKey", text, null, CanonicalJson.Serialize(key)));
        }, ct);
    }

    public Task<CommandResult> RevokeApiKeyAsync(RevokeApiKey c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var id = c.KeyId.ToString(CultureInfo.InvariantCulture);
        var spec = new CommandSpec(SourceContext, nameof(RevokeApiKey), Permissions.InterchangeManage, ResourceRef.Of("ApiKey", id), ReasonRequired: true);
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var key = (await uow.Store<IInterchangeLookup>().ListApiKeysAsync(ct)).FirstOrDefault(k => k.KeyId == c.KeyId)
                ?? throw new CommandRejectedException("key_not_found", $"API key {id} does not exist.");
            if (!await uow.Store<IInterchangeStore>().RevokeApiKeyAsync(c.KeyId, now, context.Actor, ct))
                return CommandOutcome.NoChange(CommandResult.NoChange(id, $"API key {key.Prefix}… is already revoked."));
            return new CommandOutcome(CommandResult.Ok(id, $"API key {key.Prefix}… revoked; it no longer works."),
                [pipeline.Event(new TradingPartnerChanged(key.PartnerCode, "KeyRevoked"), context, SourceContext, "TradingPartner", key.PartnerCode)],
                new AuditChange("ApiKey", id, "Active", "Revoked"));
        }, ct);
    }

    public Task<CommandResult> ReceiveAsync(ReceiveDocuments c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var spec = new CommandSpec(SourceContext, nameof(ReceiveDocuments), Permissions.InterchangeReceive, ResourceRef.Of(Document));
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            IReadOnlyList<X12Interchange> interchanges;
            try { interchanges = X12.Parse(c.Content ?? string.Empty); }
            catch (X12FormatException ex) { throw new CommandRejectedException("invalid_x12", ex.Message); }
            var lookup = uow.Store<IInterchangeLookup>();
            var store = uow.Store<IInterchangeStore>();
            var events = new List<EventEnvelope>();
            var ids = new List<long>();
            var duplicates = 0;
            foreach (var isa in interchanges)
            {
                var partner = await lookup.FindPartnerByEdiAsync(isa.SenderQualifier, isa.SenderId, ct)
                    ?? throw new CommandRejectedException("unknown_partner", $"No partner sends as {isa.SenderQualifier}/{isa.SenderId}.");
                if (c.PartnerCode is { } apiPartner && !string.Equals(apiPartner, partner.Code, StringComparison.Ordinal))
                    throw new CommandRejectedException("wrong_sender", $"The file is from {partner.Code}, not from the key's partner {apiPartner}.");
                if (!partner.Active) throw new CommandRejectedException("partner_inactive", $"Partner {partner.Code} is inactive.");
                if (!string.Equals(isa.ReceiverQualifier, partner.OurQualifier, StringComparison.Ordinal) || !string.Equals(isa.ReceiverId, partner.OurId, StringComparison.Ordinal))
                    throw new CommandRejectedException("wrong_receiver", $"The file is addressed to {isa.ReceiverQualifier}/{isa.ReceiverId}, not to us as {partner.Code} knows us ({partner.OurQualifier}/{partner.OurId}).");
                foreach (var group in isa.Groups)
                    foreach (var t in group.Transactions)
                    {
                        var known = t.Code is "850" or "855" or "856" or "860" or "810" or "997";
                        var document = new InterchangeDocument(0, DocumentDirection.Inbound, partner.Code, t.Code, isa.ControlNumber, group.ControlNumber, t.ControlNumber,
                            known ? DocumentStatus.Received : DocumentStatus.NeedsReview, null, known ? null : $"Forge does not read transaction set {t.Code}.",
                            known ? [] : [$"Unsupported transaction set {t.Code}."], c.FileName, Render(t), now, context.Actor, null, null);
                        if (await store.InsertInboundAsync(document, ct) is not { } id) { duplicates++; continue; }
                        ids.Add(id);
                        events.Add(Changed(id, document, context, $"{partner.Name} sent {Describe(t.Code)} {t.ControlNumber}{(isa.Test ? " (test)" : string.Empty)}."));
                    }
            }

            if (ids.Count == 0)
                return CommandOutcome.NoChange(CommandResult.NoChange("interchange", $"Nothing new: {duplicates} document(s) were already received."));
            var text = string.Join(",", ids.Select(i => i.ToString(CultureInfo.InvariantCulture)));
            return new CommandOutcome(CommandResult.Ok(text, $"{ids.Count} document(s) received{(duplicates > 0 ? $", {duplicates} already received" : string.Empty)}."),
                events, new AuditChange(Document, text, null, c.FileName ?? "(upload)"));
        }, ct);
    }

    public Task<CommandResult> CompleteInboundAsync(CompleteInbound c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var id = c.DocumentId.ToString(CultureInfo.InvariantCulture);
        var spec = new CommandSpec(SourceContext, nameof(CompleteInbound), Permissions.InterchangeProcess, ResourceRef.Of(Document, id));
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            if (c.Status is not (DocumentStatus.Processed or DocumentStatus.NeedsReview)) throw new CommandRejectedException("invalid_status", "An inbound document is processed or needs review.");
            var doc = await uow.Store<IInterchangeLookup>().FindDocumentAsync(c.DocumentId, ct) ?? throw new CommandRejectedException("document_not_found", $"Document {id} does not exist.");
            if (doc.Direction != DocumentDirection.Inbound || doc.Status != DocumentStatus.Received)
                return CommandOutcome.NoChange(CommandResult.NoChange(id, $"Document {id} is {doc.Status}."));
            var problems = (c.Problems ?? []).Take(50).ToList();
            await uow.Store<IInterchangeStore>().UpdateDocumentAsync(c.DocumentId, c.Status, c.Summary, problems, c.BusinessRef, doc.FileName, now, context.Actor, ct);
            var updated = doc with { Status = c.Status, BusinessRef = c.BusinessRef, Summary = c.Summary };
            var message = c.Status == DocumentStatus.NeedsReview
                ? $"{Describe(doc.TransactionSet)} {doc.TransactionControl} from {doc.PartnerCode} needs review: {string.Join(" ", problems)}"
                : c.Summary;
            return new CommandOutcome(CommandResult.Ok(id, message), [Changed(c.DocumentId, updated, context, message)],
                new AuditChange(Document, id, nameof(DocumentStatus.Received), c.Status.ToString()));
        }, ct);
    }

    public Task<CommandResult> ReprocessAsync(ReprocessDocument c, CommandContext context, CancellationToken ct) =>
        ReviewAsync(nameof(ReprocessDocument), c.DocumentId, c, context, false, DocumentStatus.Received, ct);

    public Task<CommandResult> RejectAsync(RejectDocument c, CommandContext context, CancellationToken ct) =>
        ReviewAsync(nameof(RejectDocument), c.DocumentId, c, context, true, DocumentStatus.Rejected, ct);

    public Task<CommandResult> CloseAsync(CloseDocument c, CommandContext context, CancellationToken ct) =>
        ReviewAsync(nameof(CloseDocument), c.DocumentId, c, context, true, DocumentStatus.Processed, ct);

    private Task<CommandResult> ReviewAsync<T>(string type, long documentId, T command, CommandContext context, bool reason, DocumentStatus to, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(command);
        var id = documentId.ToString(CultureInfo.InvariantCulture);
        var spec = new CommandSpec(SourceContext, type, Permissions.InterchangeReview, ResourceRef.Of(Document, id), reason);
        return pipeline.ExecuteAsync(spec, command, context, async (uow, now) =>
        {
            var doc = await uow.Store<IInterchangeLookup>().FindDocumentAsync(documentId, ct) ?? throw new CommandRejectedException("document_not_found", $"Document {id} does not exist.");
            if (doc.Direction != DocumentDirection.Inbound || doc.Status != DocumentStatus.NeedsReview)
                throw new CommandRejectedException("not_in_review", $"Document {id} is {doc.Status}; only a document that needs review can be reprocessed or rejected.");
            if (to == DocumentStatus.Received && doc.TransactionSet is not ("850" or "855" or "856" or "860" or "810" or "997"))
                throw new CommandRejectedException("unsupported", $"Forge does not read transaction set {doc.TransactionSet}; reject it.");
            var summary = to switch { DocumentStatus.Rejected => $"Rejected: {context.Reason}", DocumentStatus.Processed => $"Handled: {context.Reason}", _ => "Reprocessing" };
            await uow.Store<IInterchangeStore>().UpdateDocumentAsync(documentId, to, summary, [], doc.BusinessRef, doc.FileName, now, context.Actor, ct);
            var message = to switch { DocumentStatus.Rejected => $"Document {id} rejected.", DocumentStatus.Processed => $"Document {id} closed as handled.", _ => $"Document {id} will be processed again." };
            return new CommandOutcome(CommandResult.Ok(id, message),
                [pipeline.Event(new InterchangeDocumentReviewed(documentId, to.ToString()), context, SourceContext, Document, id), Changed(documentId, doc with { Status = to }, context, message)],
                new AuditChange(Document, id, doc.Status.ToString(), to.ToString()));
        }, ct);
    }

    public Task<CommandResult> QueueOutboundAsync(QueueOutbound c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var spec = new CommandSpec(SourceContext, nameof(QueueOutbound), Permissions.InterchangeProcess, ResourceRef.Of(Document));
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var partner = await uow.Store<IInterchangeLookup>().FindPartnerAsync(c.PartnerCode, ct) ?? throw new CommandRejectedException("partner_not_found", $"Partner {c.PartnerCode} does not exist.");
            if (!partner.UsesEdi) throw new CommandRejectedException("edi_ids_required", $"Partner {partner.Code} has no EDI ids.");
            var store = uow.Store<IInterchangeStore>();
            if (await store.OutboundExistsAsync(partner.Code, c.TransactionSet, c.BusinessRef, ct))
                return CommandOutcome.NoChange(CommandResult.NoChange(c.BusinessRef, $"{Describe(c.TransactionSet)} for {c.BusinessRef} was already written."));
            var control = await store.NextControlAsync(partner.Code, ct);
            var content = X12.Write(partner.OurQualifier!, partner.OurId!, partner.EdiQualifier!, partner.EdiId!, control, control, c.TransactionSet, c.Body, now, partner.Test);
            var number = control.ToString("D9", CultureInfo.InvariantCulture);
            var document = new InterchangeDocument(0, DocumentDirection.Outbound, partner.Code, c.TransactionSet, number, control.ToString(CultureInfo.InvariantCulture), "0001",
                DocumentStatus.Ready, c.BusinessRef, c.Summary, [], null, content, now, context.Actor, null, null);
            var id = await store.InsertOutboundAsync(document, ct) ?? throw new CommandRejectedException("duplicate", "The document was written at the same time by another run.");
            var text = id.ToString(CultureInfo.InvariantCulture);
            var message = $"{Describe(c.TransactionSet)} for {partner.Name} written: {c.Summary}";
            return new CommandOutcome(CommandResult.Ok(text, message), [Changed(id, document, context, message)], new AuditChange(Document, text, null, c.BusinessRef));
        }, ct);
    }

    public Task<CommandResult> MarkSentAsync(MarkDocumentSent c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var id = c.DocumentId.ToString(CultureInfo.InvariantCulture);
        var spec = new CommandSpec(SourceContext, nameof(MarkDocumentSent), Permissions.InterchangeProcess, ResourceRef.Of(Document, id));
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var doc = await uow.Store<IInterchangeLookup>().FindDocumentAsync(c.DocumentId, ct) ?? throw new CommandRejectedException("document_not_found", $"Document {id} does not exist.");
            if (doc.Status != DocumentStatus.Ready) return CommandOutcome.NoChange(CommandResult.NoChange(id, $"Document {id} is {doc.Status}."));
            await uow.Store<IInterchangeStore>().UpdateDocumentAsync(c.DocumentId, DocumentStatus.Sent, doc.Summary, [], doc.BusinessRef, c.FileName, now, context.Actor, ct);
            var message = $"{Describe(doc.TransactionSet)} {doc.InterchangeControl} placed in the outbox as {c.FileName}.";
            return new CommandOutcome(CommandResult.Ok(id, message), [Changed(c.DocumentId, doc with { Status = DocumentStatus.Sent }, context, message)],
                new AuditChange(Document, id, nameof(DocumentStatus.Ready), nameof(DocumentStatus.Sent)));
        }, ct);
    }

    public Task<CommandResult> AcknowledgeOutboundAsync(AcknowledgeOutbound c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var spec = new CommandSpec(SourceContext, nameof(AcknowledgeOutbound), Permissions.InterchangeProcess, ResourceRef.Of(Document));
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var store = uow.Store<IInterchangeStore>();
            var doc = await store.FindOutboundByGroupAsync(c.PartnerCode, c.GroupControl, ct);
            if (doc is null || doc.Status is not (DocumentStatus.Ready or DocumentStatus.Sent))
                return CommandOutcome.NoChange(CommandResult.NoChange(c.GroupControl, "No sent document waits for this acknowledgment."));
            var to = c.Accepted ? DocumentStatus.Accepted : DocumentStatus.Refused;
            await store.UpdateDocumentAsync(doc.DocumentId, to, doc.Summary, c.Accepted ? [] : [c.Note], doc.BusinessRef, doc.FileName, now, context.Actor, ct);
            var id = doc.DocumentId.ToString(CultureInfo.InvariantCulture);
            var message = $"{c.PartnerCode} {(c.Accepted ? "accepted" : "rejected")} {Describe(doc.TransactionSet)} {doc.InterchangeControl}{(c.Accepted ? "." : $": {c.Note}")}";
            return new CommandOutcome(CommandResult.Ok(id, message), [Changed(doc.DocumentId, doc with { Status = to }, context, message)],
                new AuditChange(Document, id, doc.Status.ToString(), to.ToString()));
        }, ct);
    }

    public Task<CommandResult> SaveWebhookAsync(SaveWebhook c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var spec = new CommandSpec(SourceContext, nameof(SaveWebhook), Permissions.InterchangeManage, ResourceRef.Of("Webhook", c.WebhookId), ReasonRequired: true);
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var name = BusinessCode.RequireName(c.Name, "Webhook");
            if (!Uri.TryCreate(c.Url?.Trim(), UriKind.Absolute, out var url) || url.Scheme != Uri.UriSchemeHttps || !string.IsNullOrEmpty(url.UserInfo))
                throw new CommandRejectedException("invalid_url", "A webhook needs an https:// address without a user name or password in it.");
            var events = (c.Events ?? []).Distinct(StringComparer.Ordinal).OrderBy(e => e, StringComparer.Ordinal).ToList();
            if (events.Count == 0 || events.Any(e => !WebhookEvents.Catalog.ContainsKey(e)))
                throw new CommandRejectedException("invalid_events", $"Choose one or more of: {string.Join(", ", WebhookEvents.Catalog.Keys)}.");
            string? partner = null;
            if (!string.IsNullOrWhiteSpace(c.PartnerCode))
            {
                var p = await uow.Store<IInterchangeLookup>().FindPartnerAsync(BusinessCode.Require(c.PartnerCode, "Partner"), ct)
                    ?? throw new CommandRejectedException("partner_not_found", $"Partner {c.PartnerCode} does not exist.");
                if (p.Kind == PartnerKind.System) throw new CommandRejectedException("invalid_partner", "Limit a webhook to a customer or supplier partner, or leave it for every event.");
                partner = p.Code;
            }

            var existing = c.WebhookId is { } wid ? (await uow.Store<IInterchangeLookup>().ListWebhooksAsync(ct)).FirstOrDefault(w => w.WebhookId == wid)
                ?? throw new CommandRejectedException("webhook_not_found", $"Webhook {wid} does not exist.") : null;
            if (existing is null && (c.Secret is null || c.Secret.Length < 32)) throw new CommandRejectedException("secret_required", "A new webhook needs its signing secret.");
            var hook = new WebhookInfo(existing?.WebhookId ?? 0, name, url.ToString(), events, partner, c.Active, c.Secret is null ? existing!.SecretPrefix : c.SecretPrefix ?? c.Secret[..8], context.Actor, now);
            var id = await uow.Store<IInterchangeStore>().SaveWebhookAsync(hook, c.Secret, ct);
            var text = id.ToString(CultureInfo.InvariantCulture);
            return new CommandOutcome(CommandResult.Ok(text, $"Webhook {name} {(existing is null ? "added" : "updated")}: {string.Join(", ", events)}{(c.Active ? string.Empty : " (inactive)")}."),
                [pipeline.Event(new TradingPartnerChanged(partner ?? "-", existing is null ? "WebhookAdded" : "WebhookUpdated"), context, SourceContext, "Webhook", text)],
                new AuditChange("Webhook", text, existing is null ? null : CanonicalJson.Serialize(existing), CanonicalJson.Serialize(hook with { WebhookId = id })));
        }, ct);
    }

    public Task<CommandResult> EnqueueDeliveriesAsync(EnqueueDeliveries c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var spec = new CommandSpec(SourceContext, nameof(EnqueueDeliveries), Permissions.InterchangeProcess, ResourceRef.Of("WebhookDelivery"));
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var ids = await uow.Store<IInterchangeStore>().InsertDeliveriesAsync(c.WebhookIds ?? [], c.EventSequence, c.EventName, c.Payload, now, ct);
            return ids.Count == 0
                ? CommandOutcome.NoChange(CommandResult.NoChange("webhooks", "Already queued."))
                : new CommandOutcome(CommandResult.Ok(string.Join(",", ids.Select(i => i.ToString(CultureInfo.InvariantCulture))), $"{ids.Count} webhook delivery(ies) queued."), [], null);
        }, ct);
    }

    public Task<CommandResult> RecordDeliveryAttemptAsync(RecordDeliveryAttempt c, CommandContext context, CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(c);
        var id = c.DeliveryId.ToString(CultureInfo.InvariantCulture);
        var spec = new CommandSpec(SourceContext, nameof(RecordDeliveryAttempt), Permissions.InterchangeProcess, ResourceRef.Of("WebhookDelivery", id));
        return pipeline.ExecuteAsync(spec, c, context, async (uow, now) =>
        {
            var store = uow.Store<IInterchangeStore>();
            var d = await store.FindDeliveryAsync(c.DeliveryId, ct) ?? throw new CommandRejectedException("delivery_not_found", $"Delivery {id} does not exist.");
            if (d.Status != DeliveryStatus.Pending) return CommandOutcome.NoChange(CommandResult.NoChange(id, $"Delivery {id} is {d.Status}."));
            var attempts = d.Attempts + 1;
            var error = c.Error is null ? null : (c.Error.Length > 500 ? c.Error[..500] : c.Error);
            if (c.Delivered)
            {
                await store.UpdateDeliveryAsync(c.DeliveryId, DeliveryStatus.Delivered, attempts, d.NextAttemptAt, c.StatusCode, null, now, ct);
                return new CommandOutcome(CommandResult.Ok(id, $"Delivered on attempt {attempts}."), [], null);
            }

            if (attempts > RetryDelays.Count)
            {
                await store.UpdateDeliveryAsync(c.DeliveryId, DeliveryStatus.Failed, attempts, d.NextAttemptAt, c.StatusCode, error, null, ct);
                var message = $"Webhook delivery {id} ({d.EventName}) failed after {attempts} attempts: {error ?? $"HTTP {c.StatusCode}"}.";
                return new CommandOutcome(CommandResult.Ok(id, message),
                    [pipeline.Event(new WebhookDeliveryFailed(c.DeliveryId, d.WebhookId, d.EventName, message), context, SourceContext, "WebhookDelivery", id)],
                    new AuditChange("WebhookDelivery", id, nameof(DeliveryStatus.Pending), nameof(DeliveryStatus.Failed)));
            }

            await store.UpdateDeliveryAsync(c.DeliveryId, DeliveryStatus.Pending, attempts, now + RetryDelays[attempts - 1], c.StatusCode, error, null, ct);
            return new CommandOutcome(CommandResult.Ok(id, $"Attempt {attempts} failed; retrying."), [], null);
        }, ct);
    }

