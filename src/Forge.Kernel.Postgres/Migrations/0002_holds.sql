-- V3.10: generalized holds (V3 brief AS).
--
-- A hold has a kind (quality, material, production, engineering, customer, shipping, procurement, configuration,
-- safety, administrative), a target (an order, operation, part, lot, work center, machine, supplier, purchase order,
-- shipment or program), a source, evidence, the records it affects and the resolution it needs. Each kind blocks the
-- downstream activities configured for it and has its own release authority. A hold is released once, with a
-- reason; nothing else about it ever changes. Holds live in the kernel because every context checks them.

CREATE TABLE kernel.hold_kind (
    kind                text PRIMARY KEY CHECK (kind IN ('Quality', 'Material', 'Production', 'Engineering', 'Customer', 'Shipping', 'Procurement', 'Configuration', 'Safety', 'Administrative')),
    blocks              text[] NOT NULL CHECK (cardinality(blocks) > 0 AND blocks <@ ARRAY['ReleaseOrder', 'StartWork', 'ReportOutput', 'IssueMaterial', 'Ship', 'Purchase', 'Receive']),
    release_permission  text NOT NULL,
    changed_at          timestamptz NOT NULL,
    changed_by          text NOT NULL
);
INSERT INTO kernel.hold_kind (kind, blocks, release_permission, changed_at, changed_by) VALUES
    ('Quality', '{StartWork,ReportOutput,IssueMaterial,Ship}', 'quality.disposition', now(), 'system'),
    ('Material', '{IssueMaterial,StartWork,Ship}', 'inventory.approve', now(), 'system'),
    ('Production', '{StartWork,ReportOutput}', 'holds.production.release', now(), 'system'),
    ('Engineering', '{ReleaseOrder,StartWork}', 'engineering.release', now(), 'system'),
    ('Customer', '{ReleaseOrder,Ship}', 'programs.manage', now(), 'system'),
    ('Shipping', '{Ship}', 'inventory.shipping.ship', now(), 'system'),
    ('Procurement', '{Purchase,Receive}', 'procurement.approve', now(), 'system'),
    ('Configuration', '{ReleaseOrder,StartWork,Ship}', 'engineering.changes.approve', now(), 'system'),
    ('Safety', '{StartWork}', 'safety.rules.approve', now(), 'system'),
    ('Administrative', '{ReleaseOrder,StartWork,ReportOutput,IssueMaterial,Ship,Purchase,Receive}', 'kernel.access.manage', now(), 'system');

CREATE TABLE kernel.hold (
    hold_id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 501) PRIMARY KEY,
    kind                 text NOT NULL REFERENCES kernel.hold_kind(kind),
    target_type          text NOT NULL CHECK (target_type IN ('Order', 'Operation', 'Part', 'Lot', 'WorkCenter', 'Machine', 'Supplier', 'PurchaseOrder', 'Shipment', 'Program')),
    target_id            text NOT NULL,
    target_part          text NULL CHECK (target_part IS NULL OR target_type = 'Lot'),
    source               text NOT NULL,
    reason               text NOT NULL,
    evidence             text NULL,
    affected_records     text[] NOT NULL DEFAULT '{}',
    required_resolution  text NOT NULL,
    placed_at            timestamptz NOT NULL,
    placed_by            text NOT NULL,
    released_at          timestamptz NULL,
    released_by          text NULL,
    release_reason       text NULL,
    CHECK ((released_at IS NULL) = (released_by IS NULL) AND (released_at IS NULL) = (release_reason IS NULL))
);
CREATE INDEX hold_active ON kernel.hold (target_type, target_id) WHERE released_at IS NULL;

CREATE FUNCTION kernel.hold_release_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' OR OLD.released_at IS NOT NULL
       OR (NEW.hold_id, NEW.kind, NEW.target_type, NEW.target_id, NEW.target_part, NEW.source, NEW.reason, NEW.evidence, NEW.affected_records, NEW.required_resolution, NEW.placed_at, NEW.placed_by)
          IS DISTINCT FROM (OLD.hold_id, OLD.kind, OLD.target_type, OLD.target_id, OLD.target_part, OLD.source, OLD.reason, OLD.evidence, OLD.affected_records, OLD.required_resolution, OLD.placed_at, OLD.placed_by) THEN
        RAISE EXCEPTION 'hold % is only ever released, once', OLD.hold_id;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER hold_release_only BEFORE UPDATE OR DELETE ON kernel.hold
    FOR EACH ROW EXECUTE FUNCTION kernel.hold_release_only();
